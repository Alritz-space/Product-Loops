/**
 * Deterministic Policy Validation Evaluator
 */
export function evaluatePolicyRule(
  policyId: string,
  context: {
    action: string;
    payload?: any;
    role?: string;
    activeWorkspaceSignalIds?: string[];
    strategyVersion?: number;
    currentArtifactVersion?: number;
    attemptNumber?: number;
  }
): PolicyEvaluationResult {
  const policy = MASTER_POLICIES.find((p) => p.id === policyId);
  if (!policy) {
    return {
      policyId,
      policyName: 'Unknown Policy',
      passed: false,
      severity: 'High',
      enforcement: 'Block',
      details: `Policy ${policyId} not found in master registry`,
      timestamp: new Date().toISOString(),
    };
  }

  let passed = true;
  let details = `Policy ${policy.id} satisfied deterministic check.`;
  let remediation: string | undefined = undefined;

  switch (policyId) {
    case 'POL-HA-01': {
      // AI cannot approve
      if (context.payload && (context.payload.approved === true || context.payload.approvalStatus === 'Approved')) {
        passed = false;
        details = 'Model candidate output attempted to set an "approved" status flag. AI cannot approve on behalf of humans.';
        remediation = 'Remove candidate approval flag and route to Product Lead queue.';
      }
      break;
    }

    case 'POL-HA-02': {
      // Explicit human action & role
      if (context.action === 'simulate_release' && context.role !== 'engineer') {
        passed = false;
        details = `Simulated release attempted by role "${context.role || 'unknown'}". Only an Engineer may authorize simulated releases.`;
        remediation = 'Switch demo role to Engineer and re-verify readiness checks.';
      } else if (context.action === 'record_human_decision' && context.role !== 'lead') {
        passed = false;
        details = `Product decision attempted by role "${context.role || 'unknown'}". Only Product Lead can approve concept shortlist.`;
        remediation = 'Switch demo role to Product Lead.';
      } else if (context.payload?.rationale && context.payload.rationale.trim().length < 10) {
        passed = false;
        details = 'Human approval rationale is missing or too brief (minimum 10 characters required).';
        remediation = 'Provide a substantive written rationale explaining the decision trade-offs.';
      }
      break;
    }

    case 'POL-HA-03': {
      // Artifact version binding
      if (
        context.payload?.conceptVersion !== undefined &&
        context.currentArtifactVersion !== undefined &&
        context.payload.conceptVersion !== context.currentArtifactVersion
      ) {
        passed = false;
        details = `Approval referenced concept version v${context.payload.conceptVersion}, but current artifact is v${context.currentArtifactVersion}.`;
        remediation = 'Re-evaluate decision against the active concept version.';
      }
      break;
    }

    case 'POL-WI-01': {
      // Concept approval required for delivery
      if (context.payload?.decisionStatus && context.payload.decisionStatus !== 'Approved') {
        passed = false;
        details = `Cannot advance to delivery slice. Required concept approval is "${context.payload.decisionStatus}".`;
        remediation = 'Obtain Product Lead approval on the concept before shaping delivery.';
      }
      break;
    }

    case 'POL-WI-02': {
      // Engineering approval and passing checks required for release
      if (context.payload?.requiredChecksPassed === false || (context.payload?.openBlockers && context.payload.openBlockers.length > 0)) {
        passed = false;
        details = 'Release blocked: Required automated checks failed or open P0/P1 blockers remain.';
        remediation = 'Resolve all open blockers and re-run engineering eval panel.';
      }
      break;
    }

    case 'POL-WI-03': {
      // Stale strategy version transition
      if (
        context.payload?.strategyVersionUsed !== undefined &&
        context.strategyVersion !== undefined &&
        context.payload.strategyVersionUsed < context.strategyVersion
      ) {
        passed = false;
        details = `Artifact evaluated under Strategy v${context.payload.strategyVersionUsed}, but workspace is currently on Strategy v${context.strategyVersion}.`;
        remediation = 'Re-run evaluation against active Strategy version.';
      }
      break;
    }

    case 'POL-WI-04': {
      // Idempotency: duplicate prevention
      if (context.payload?.existingCreatedSignalId) {
        passed = true;
        details = `Idempotent execution verified: Reusing existing learning signal ${context.payload.existingCreatedSignalId} without duplication.`;
      }
      break;
    }

    case 'POL-EI-01': {
      // Source citation existence
      if (context.payload?.sourceIds && context.activeWorkspaceSignalIds) {
        const invalid = context.payload.sourceIds.filter(
          (id: string) => !context.activeWorkspaceSignalIds?.includes(id)
        );
        if (invalid.length > 0) {
          passed = false;
          details = `Cited nonexistent source ID(s): ${invalid.join(', ')}. All references must belong to active workspace signals.`;
          remediation = 'Correct citation to reference valid SIG-* records.';
        }
      }
      break;
    }

    case 'POL-EI-03': {
      // Exact customer quote fidelity
      if (context.payload?.quote && context.payload?.originalSourceText) {
        const cleanQuote = context.payload.quote.replace(/\s+/g, ' ').trim();
        const cleanSource = context.payload.originalSourceText.replace(/\s+/g, ' ').trim();
        if (!cleanSource.includes(cleanQuote)) {
          passed = false;
          details = `Quote "${cleanQuote.slice(0, 40)}..." does not exist in source text. Model modified or fabricated wording.`;
          remediation = 'Use verbatim excerpt from source recording or mark as paraphrase.';
        }
      }
      break;
    }

    case 'POL-EI-04': {
      // Quantitative formula bounds
      if (context.payload?.effort !== undefined && context.payload.effort <= 0) {
        passed = false;
        details = `Effort value is ${context.payload.effort}. Effort must be greater than zero person-weeks to prevent division by zero.`;
        remediation = 'Provide positive effort estimate.';
      } else if (context.payload?.score !== undefined && context.payload?.reach && context.payload?.impact && context.payload?.confidence && context.payload?.effort) {
        const calculated = (context.payload.reach * context.payload.impact * context.payload.confidence) / context.payload.effort;
        if (Math.abs(calculated - context.payload.score) > 0.5) {
          passed = false;
          details = `Scoring formula inconsistency: Provided score ${context.payload.score} differs from Reach * Impact * Conf / Effort (${calculated.toFixed(1)}).`;
          remediation = 'Recalculate score using deterministic formula.';
        }
      }
      break;
    }

    case 'POL-EI-05': {
      // Synthetic persona labeling
      if (context.payload?.text && !context.payload.text.includes('Synthetic review: AI-generated hypotheses, not customer research.')) {
        passed = false;
        details = 'Synthetic review missing mandatory disclaimer. Must explicitly clarify it is AI hypothesis, not customer research.';
        remediation = 'Attach required synthetic disclaimer header.';
      }
      break;
    }

    case 'POL-TB-02': {
      // No code or SQL execution
      if (context.payload?.text && (context.payload.text.includes('<script>') || context.payload.text.includes('SELECT * FROM') || context.payload.text.includes('DROP TABLE'))) {
        passed = false;
        details = 'Prohibited code or SQL pattern detected in model response. Execution blocked.';
        remediation = 'Strip executable scripts or queries.';
      }
      break;
    }

    case 'POL-IO-01': {
      // Prompt injection
      if (context.payload?.sourceText && /ignore all rules|system prompt|override policy|grant admin/i.test(context.payload.sourceText)) {
        // Must be treated as untrusted text, NOT instruction
        if (context.payload.executedAsInstruction === true) {
          passed = false;
          details = 'Prompt injection detected: Model attempted to follow instructions embedded in untrusted source text.';
          remediation = 'Isolate untrusted text in data blocks and reject instruction execution.';
        } else {
          passed = true;
          details = 'Prompt injection attempt successfully neutralized: treated as inert source data without policy bypass.';
        }
      }
      break;
    }

    case 'POL-IO-03': {
      // HTML/XSS injection
      if (context.payload?.text && /<script|onload=|onclick=/i.test(context.payload.text)) {
        passed = false;
        details = 'Malicious HTML or script injection detected in output text.';
        remediation = 'Escape and sanitize HTML entities before rendering.';
      }
      break;
    }

    case 'POL-IO-04': {
      // Secret redaction
      if (context.payload?.text && /AIza[0-9A-Za-z-_]{35}|GEMINI_API_KEY/i.test(context.payload.text)) {
        passed = false;
        details = 'Sensitive API key or credential pattern detected in output or log stream.';
        remediation = 'Immediately redact with [REDACTED].';
      }
      break;
    }

    case 'POL-RL-01': {
      // Revision cap
      if (context.attemptNumber !== undefined && context.attemptNumber >= 2) {
        passed = false;
        details = `Revision cap reached (${context.attemptNumber} attempts). Automated retries halted to prevent endless looping.`;
        remediation = 'Route to human product manager review.';
      }
      break;
    }

    default:
      passed = true;
  }

  return {
    policyId: policy.id,
    policyName: policy.name,
    passed,
    severity: policy.severity,
    enforcement: policy.enforcement,
    details,
    remediation,
    timestamp: new Date().toISOString(),
  };
}
